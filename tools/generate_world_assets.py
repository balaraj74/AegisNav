"""Regenerate the occupancy map (PGM) and the SDF wall models from the core scenario grid.

The grid in aegisnav_core.scenarios.corridor_scenario is the single source of truth for
static geometry; run this after changing it. `aegisnav_bringup/test/test_assets.py`
fails if the files and the grid disagree.
Usage: PYTHONPATH=ros2_ws/src/aegisnav_core python3 tools/generate_world_assets.py
"""
from __future__ import annotations

import re
import struct
import zlib
from pathlib import Path

from aegisnav_core.models import Cell
from aegisnav_core.scenarios import corridor_scenario, rescue_building_scenario, rescue_compound_scenario
from world_rescue_building import rescue_world_sdf

ROOT = Path(__file__).resolve().parents[1]
BRINGUP = ROOT / "ros2_ws/src/aegisnav_bringup"
# Interior walls are low enough to read the scene from an oblique camera; both heights stay well
# above the 0.28 m lidar plane, so sensing is unchanged. The perimeter also hides exterior props.
WALL_HEIGHT_M = 0.7
PERIMETER_HEIGHT_M = 1.0
WALL_MATERIAL = ("<material><ambient>0.42 0.40 0.37 1.0</ambient><diffuse>0.62 0.60 0.56 1.0</diffuse>"
                 "<specular>0.10 0.10 0.10 1</specular></material>")
DECOR_BEGIN, DECOR_END = "    <!-- aegisnav:decor:begin -->\n", "    <!-- aegisnav:decor:end -->\n"
# Flat floor markings stay below 1 cm (lidar plane is 0.28 m). Exterior props sit outside the
# 1.4 m perimeter wall, so the 2D lidar inside the arena cannot see them.
FLAT_Z = 0.003


# Particle colour-over-lifetime ramps (left = birth, right = death), sampled by Gazebo's particle
# emitter like fog_emitter/fogcolors.png. Keys: lifetime fraction -> RGBA (0-255).
EFFECTS_TEXTURES = BRINGUP / "models/aegisnav_effects/materials/textures"
FIRE_RAMP = ((0.0, (255, 244, 190, 255)), (0.18, (255, 205, 70, 250)), (0.42, (250, 115, 25, 235)),
             (0.68, (160, 35, 12, 180)), (0.86, (65, 58, 52, 90)), (1.0, (45, 45, 45, 0)))
SMOKE_RAMP = ((0.0, (48, 45, 43, 210)), (0.5, (78, 76, 74, 150)), (1.0, (115, 115, 115, 0)))
GAS_RAMP = ((0.0, (150, 205, 70, 0)), (0.25, (140, 200, 65, 120)), (0.7, (120, 175, 60, 80)), (1.0, (110, 150, 60, 0)))


def png_rgba(width: int, height: int, pixels: list[tuple[int, int, int, int]]) -> bytes:
    """Minimal RGBA PNG encoder (stdlib only); pixels are row-major."""
    def chunk(tag: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    rows = b"".join(b"\0" + bytes(c for px in pixels[y * width:(y + 1) * width] for c in px) for y in range(height))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))


def color_ramp(stops, width: int = 64) -> list[tuple[int, int, int, int]]:
    out = []
    for i in range(width):
        t = i / (width - 1)
        (t0, c0), (t1, c1) = next((a, b) for a, b in zip(stops, stops[1:]) if t <= b[0])
        f = (t - t0) / (t1 - t0)
        out.append(tuple(round(a + (b - a) * f) for a, b in zip(c0, c1)))
    return out


FINE_UPSAMPLE = 8  # 0.4 m planning cells -> 0.05 m localization pixels


def pgm_text(grid, upsample: int = 1) -> str:
    """ASCII PGM of the grid; each planning cell becomes upsample x upsample pixels."""
    rows = []
    for py in reversed(range(grid.height * upsample)):  # PGM row 0 is the top (max y) of the map
        y = py // upsample
        rows.append(" ".join("0" if grid.is_blocked(Cell(px // upsample, y)) else "254" for px in range(grid.width * upsample)))
    header = "P2\n# AegisNav bounded rescue test map; generated by tools/generate_world_assets.py from the core grid.\n"
    return header + f"{grid.width * upsample} {grid.height * upsample}\n255\n" + "\n".join(rows) + "\n"


def map_yaml(image: str, resolution: float, grid) -> str:
    return (f"image: {image}\nmode: trinary\nresolution: {resolution}\n"
            f"origin: [{grid.origin_x_m}, {grid.origin_y_m}, 0.0]\nnegate: 0\noccupied_thresh: 0.65\nfree_thresh: 0.196\n")


def wall_models(grid) -> str:
    """One box per maximal horizontal run of blocked cells in each row."""
    out, r = [], grid.resolution_m
    for y in range(grid.height):
        x, seg = 0, 0
        while x < grid.width:
            if not grid.is_blocked(Cell(x, y)):
                x += 1
                continue
            start = x
            while x < grid.width and grid.is_blocked(Cell(x, y)):
                x += 1
            cx = grid.origin_x_m + (start + x) / 2 * r
            cy = grid.origin_y_m + (y + 0.5) * r
            perimeter = y in (0, grid.height - 1) or (x - start == 1 and start in (0, grid.width - 1))
            h = PERIMETER_HEIGHT_M if perimeter else WALL_HEIGHT_M
            size = f"{(x - start) * r:.3f} {r:.3f} {h:.3f}"
            out.append(
                f'    <model name="wall_y{y:02d}_seg{seg:02d}">\n'
                f"      <static>true</static>\n"
                f"      <pose>{cx:.3f} {cy:.3f} {h / 2:.3f} 0 0 0</pose>\n"
                f'      <link name="link">\n'
                f'        <collision name="collision"><geometry><box><size>{size}</size></box></geometry></collision>\n'
                f'        <visual name="visual"><geometry><box><size>{size}</size></box></geometry>\n'
                f"          {WALL_MATERIAL}\n"
                f"        </visual>\n"
                f"      </link>\n"
                f"    </model>\n"
            )
            seg += 1
    return "".join(out)


def _flat(name: str, x: float, y: float, sx: float, sy: float, rgb: tuple[float, float, float], emissive: float = 0.0, yaw: float = 0.0) -> str:
    r, g, b = rgb
    return (f'    <model name="{name}"><static>true</static><pose>{x:.3f} {y:.3f} {FLAT_Z} 0 0 {yaw:.3f}</pose><link name="link">'
            f'<visual name="v"><cast_shadows>false</cast_shadows><geometry><box><size>{sx:.3f} {sy:.3f} 0.004</size></box></geometry>'
            f'<material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse>'
            f'<emissive>{r * emissive:.2f} {g * emissive:.2f} {b * emissive:.2f} 1</emissive></material></visual></link></model>\n')


def doorway_cells(grid) -> list[tuple[Cell, str]]:
    """Free cells inside a wall opening (up to two cells wide).

    A cell is in an opening of a vertical wall if both horizontal neighbours are free and
    wall continues within two cells above *and* below it (and symmetrically for horizontal walls).
    """
    def blocked(x: int, y: int) -> bool:
        return grid.contains(Cell(x, y)) and grid.is_blocked(Cell(x, y))

    out = []
    for y in range(grid.height):
        for x in range(grid.width):
            if blocked(x, y) or not grid.contains(Cell(x, y)):
                continue
            free_lr = not blocked(x - 1, y) and not blocked(x + 1, y)
            free_ud = not blocked(x, y - 1) and not blocked(x, y + 1)
            in_vertical = free_lr and (blocked(x, y - 1) or blocked(x, y - 2)) and (blocked(x, y + 1) or blocked(x, y + 2))
            in_horizontal = free_ud and (blocked(x - 1, y) or blocked(x - 2, y)) and (blocked(x + 1, y) or blocked(x + 2, y))
            if in_vertical:
                out.append((Cell(x, y), "x"))  # passage runs along x through a vertical wall
            elif in_horizontal:
                out.append((Cell(x, y), "y"))
    return out


def decor_models(scn) -> str:
    import random
    grid, r = scn.grid, scn.grid.resolution_m
    out = []
    pad = r * 0.9
    out.append(_flat("pad_base", *grid.cell_center_world(scn.base), pad, pad, (0.10, 0.35, 0.95), 0.35))
    out.append(_flat("pad_target", *grid.cell_center_world(scn.target), pad, pad, (1.0, 0.80, 0.10), 0.35))
    for i, c in enumerate(scn.refuges):
        out.append(_flat(f"pad_refuge_{i}", *grid.cell_center_world(c), pad, pad, (0.05, 0.80, 0.30), 0.35))
    for c, axis in doorway_cells(grid):
        x, y = grid.cell_center_world(c)
        # Yellow threshold bar across the passage, centred in the doorway cell.
        sx, sy = (0.07, r * 0.98) if axis == "x" else (r * 0.98, 0.07)
        out.append(_flat(f"threshold_{c.x}_{c.y}", x, y, sx, sy, (0.95, 0.78, 0.05), 0.2))
    # Exterior rubble ring, seeded and deterministic.
    rng = random.Random(20261102)
    half_w, half_h = grid.width * r / 2, grid.height * r / 2
    cx0, cy0 = grid.origin_x_m + half_w, grid.origin_y_m + half_h
    n = 0
    while n < 36:
        x = rng.uniform(cx0 - 7.6, cx0 + 7.6)
        y = rng.uniform(cy0 - 5.6, cy0 + 5.6)
        if abs(x - cx0) < half_w + 0.4 and abs(y - cy0) < half_h + 0.4:
            continue  # inside or touching the arena: never place props there
        kind = rng.random()
        yaw, tilt = rng.uniform(0, 3.14), rng.uniform(-0.35, 0.35)
        if kind < 0.55:
            sx, sy, sz = rng.uniform(0.3, 1.1), rng.uniform(0.2, 0.7), rng.uniform(0.1, 0.45)
            geom, col = f"<box><size>{sx:.2f} {sy:.2f} {sz:.2f}</size></box>", (0.45, 0.43, 0.40)
            z = sz / 2
        elif kind < 0.8:
            sz = rng.uniform(0.6, 1.4)
            geom, col = f"<box><size>{rng.uniform(0.8, 1.6):.2f} 0.12 {sz:.2f}</size></box>", (0.55, 0.53, 0.50)
            z, tilt = sz / 2 * 0.8, rng.uniform(0.3, 0.7)
        else:
            geom, col = "<cylinder><radius>0.18</radius><length>0.55</length></cylinder>", rng.choice(((0.70, 0.15, 0.10), (0.15, 0.30, 0.60)))
            z = 0.275
        cr, cg, cb = col
        out.append(f'    <model name="rubble_{n:02d}"><static>true</static><pose>{x:.2f} {y:.2f} {z:.2f} {tilt:.2f} 0 {yaw:.2f}</pose><link name="link">'
                   f'<collision name="c"><geometry>{geom}</geometry></collision><visual name="v"><geometry>{geom}</geometry>'
                   f'<material><ambient>{cr} {cg} {cb} 1</ambient><diffuse>{cr} {cg} {cb} 1</diffuse></material></visual></link></model>\n')
        n += 1
    return "".join(out)


def main() -> None:
    scn = corridor_scenario()
    grid = scn.grid
    # Planning grid (0.4 m): consumed by the AegisNav planner and forecaster.
    (BRINGUP / "maps/aegisnav_rescue.pgm").write_text(pgm_text(grid), encoding="ascii")
    (BRINGUP / "maps/aegisnav_rescue.yaml").write_text(map_yaml("aegisnav_rescue.pgm", grid.resolution_m, grid), encoding="ascii")
    # Same geometry at 0.05 m for AMCL, the local costmap and RViz. AMCL against the
    # 0.4 m grid was observed to mislocalize by ~0.3 m in Gazebo.
    fine_res = round(grid.resolution_m / FINE_UPSAMPLE, 6)
    (BRINGUP / "maps/aegisnav_rescue_fine.pgm").write_text(pgm_text(grid, FINE_UPSAMPLE), encoding="ascii")
    (BRINGUP / "maps/aegisnav_rescue_fine.yaml").write_text(map_yaml("aegisnav_rescue_fine.pgm", fine_res, grid), encoding="ascii")
    for world in (BRINGUP / "worlds/aegisnav_rescue.sdf", ROOT / "assets/worlds/aegisnav_rescue.sdf"):
        text = world.read_text(encoding="utf-8")
        pattern = re.compile(r'    <model name="wall_y\d\d_seg\d\d">.*?</model>\n(?=\s*(?:<model name="refuge_marker_0">|<!-- aegisnav:decor:begin -->))', re.S)
        if not pattern.search(text):
            raise SystemExit(f"wall block not found in {world}")
        text = pattern.sub(lambda _m: wall_models(grid), text, count=1)
        if DECOR_BEGIN in text:
            a, b = text.index(DECOR_BEGIN), text.index(DECOR_END) + len(DECOR_END)
            text = text[:a] + DECOR_BEGIN + decor_models(scn) + DECOR_END + text[b:]
        else:  # first run: replace the old hand-written refuge markers
            text = re.sub(r'    <model name="refuge_marker_\d">.*?</model>\n', "", text, flags=re.S)
            anchor = '    <model name="aegis_bot"'
            text = text.replace(anchor, DECOR_BEGIN + decor_models(scn) + DECOR_END + "\n" + anchor, 1)
        world.write_text(text, encoding="utf-8")
    # rescue_building / rescue_compound: whole world generated; planning map (0.5 m) + localization map (0.05 m).
    for name, rb in (("rescue_building", rescue_building_scenario()), ("rescue_compound", rescue_compound_scenario())):
        (BRINGUP / f"worlds/{name}.sdf").write_text(rescue_world_sdf(rb), encoding="utf-8")
        up = round(rb.grid.resolution_m / 0.05)
        (BRINGUP / f"maps/{name}.pgm").write_text(pgm_text(rb.grid), encoding="ascii")
        (BRINGUP / f"maps/{name}.yaml").write_text(map_yaml(f"{name}.pgm", rb.grid.resolution_m, rb.grid), encoding="ascii")
        (BRINGUP / f"maps/{name}_fine.pgm").write_text(pgm_text(rb.grid, up), encoding="ascii")
        (BRINGUP / f"maps/{name}_fine.yaml").write_text(map_yaml(f"{name}_fine.pgm", round(rb.grid.resolution_m / up, 6), rb.grid), encoding="ascii")
    EFFECTS_TEXTURES.mkdir(parents=True, exist_ok=True)
    for name, ramp in (("fire_colors.png", FIRE_RAMP), ("smoke_colors.png", SMOKE_RAMP), ("gas_colors.png", GAS_RAMP)):
        (EFFECTS_TEXTURES / name).write_bytes(png_rgba(64, 1, color_ramp(ramp)))
    print("regenerated PGM and SDF walls (corridor) and rescue_building / rescue_compound worlds + maps")


if __name__ == "__main__":
    main()
