"""Summarise batch missions from artifacts/batch/<mode>/seed_<n>/ into a Markdown report and JSON.

Usage: PYTHONPATH=ros2_ws/src/aegisnav_core python3 tools/analyze_batch.py [--batch-dir artifacts/batch]
                                                    [--out docs/simulation/batch_results.md]
A run with no finished metrics.json counts as a failure ("no_result"), never as missing data.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from aegisnav_core.batch import mean_sd, paired_bootstrap_ci, wilson_interval

MODE_ORDER = ["sensing", "sensing_notriage", "omniscient", "baseline"]
MODE_LABEL = {
    "sensing": "AegisNav, onboard sensing + triage",
    "sensing_notriage": "AegisNav, onboard sensing, fixed point order (no triage)",
    "omniscient": "AegisNav, omniscient hazards",
    "baseline": "Distance-only baseline (hazard-blind shortest path)",
}
CYCLE = re.compile(r"Planning cycle took ([0-9.]+) s")


def load_run(d: Path) -> dict:
    run = {"seed": int(d.name.split("_")[1]), "outcome": "no_result", "metrics": None, "cycles": [], "exit": ""}
    m = d / "metrics.json"
    if m.is_file():
        data = json.loads(m.read_text())
        run["data"] = data
        if data.get("done"):
            run["outcome"], run["metrics"] = data["outcome"], data["metrics"]
        else:
            run["outcome"], run["metrics"] = "no_result", data.get("metrics")
    e = d / "exit_reason.txt"
    run["exit"] = e.read_text().strip() if e.is_file() else ""
    log = d / "sim.log"
    if log.is_file():
        run["cycles"] = [float(x) for x in CYCLE.findall(log.read_text(errors="ignore"))]
    return run


def pct(vals: list[float], q: float) -> float:
    s = sorted(vals)
    return s[min(len(s) - 1, int(q * len(s)))] if s else float("nan")


def fmt_rate(k: int, n: int) -> str:
    lo, hi = wilson_interval(k, n)
    return f"{k}/{n} ({k / n:.0%}; 95% CI {lo:.0%}–{hi:.0%})" if n else "—"


def fmt_ms(vals: list[float], key: str, digits: int = 1) -> str:
    if not vals:
        return "—"
    m, sd = mean_sd(vals)
    return f"{m:.{digits}f} ± {sd:.{digits}f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch-dir", default="artifacts/batch")
    ap.add_argument("--out", default="docs/simulation/batch_results.md")
    args = ap.parse_args()
    root = Path(args.batch_dir)
    modes = {m: [load_run(d) for d in sorted((root / m).glob("seed_*"), key=lambda p: int(p.name.split("_")[1]))]
             for m in MODE_ORDER if (root / m).is_dir()}
    summary: dict = {}
    lines = ["# Batch study: full Gazebo/Nav2 missions (rescue_compound)", "",
             "Generated by `tools/analyze_batch.py` from `artifacts/batch/`. Each run is one complete headless mission in an",
             "isolated container with seeded random ignitions (`aegisnav_core.batch.randomized_ignitions`) on top of the four",
             "permanent sources. Exposure and hazard entry are measured against the **real** hazard field at the robot's AMCL",
             "position (simulated-model risk x seconds; not physical dose). Intervals are 95% Wilson (rates) or SD (means).", ""]
    lines += ["## Outcomes", "", "| Mode | Runs | Complete (all 5 points, back at base) | Reached base | Entered risk ≥ 0.92 | Stuck / timeout / no result |",
              "|---|---|---|---|---|---|"]
    for m, runs in modes.items():
        n = len(runs)
        out = [r["outcome"] for r in runs]
        complete, base = out.count("complete"), out.count("complete") + out.count("partial")
        hazard = sum(1 for r in runs if r["metrics"] and r["metrics"]["time_in_s"] > 0)
        bad = sum(1 for o in out if o in ("stuck", "timeout", "no_result"))
        fin_runs = [r for r in runs if r["metrics"] and r["outcome"] != "no_result"]
        summary[m] = {"runs": n, "outcomes": {o: out.count(o) for o in sorted(set(out))}, "complete": complete,
                      "reached_base": base, "entered_hard_risk": hazard, "failed": bad,
                      "complete_ci": list(wilson_interval(complete, n)), "entered_hard_risk_ci": list(wilson_interval(hazard, n)),
                      "exposure_by_seed": {str(r["seed"]): r["metrics"]["exposure_risk_s"] for r in fin_runs},
                      "hard_time_by_seed": {str(r["seed"]): r["metrics"]["time_in_s"] for r in fin_runs}}
        small = " **(too few runs to compare)**" if n < 5 else ""
        lines.append(f"| {MODE_LABEL[m]}{small} | {n} | {fmt_rate(complete, n)} | {fmt_rate(base, n)} | {fmt_rate(hazard, n)} | {bad} |")
    lines += ["", "## Cost of the mission (runs that finished; mean ± SD)", "",
              "| Mode | Exposure (risk·s) | Time at risk ≥ 0.5 (s) | Time at risk ≥ 0.92 (s) | Distance (m) | Mission time (s, sim) | Routes cancelled |",
              "|---|---|---|---|---|---|---|"]
    for m, runs in modes.items():
        fin = [r for r in runs if r["metrics"] and r["outcome"] != "no_result"]
        if not fin:
            continue
        col = lambda k: [r["metrics"][k] for r in fin]
        mt = [r["data"]["mission_s"] for r in fin]
        cx = [r["data"]["routes_cancelled"] for r in fin]
        lines.append(f"| {MODE_LABEL[m]} (n={len(fin)}) | {fmt_ms(col('exposure_risk_s'), '', 1)} | {fmt_ms(col('time_near_s'), '', 1)} | "
                     f"{fmt_ms(col('time_in_s'), '', 1)} | {fmt_ms(col('distance_m'), '', 0)} | {fmt_ms(mt, '', 0)} | {fmt_ms(cx, '', 1)} |")
    lines += ["", "## Closeness to fire (distance from the robot to the nearest cell at true risk ≥ 0.92)", "",
              "| Mode | Runs | Closest approach per run, m (min / median / max) | Runs that came within 1.0 m | Seconds within 1.0 m per run (mean) |", "|---|---|---|---|---|"]
    for m, runs in modes.items():
        d = [r["data"] for r in runs if r.get("data") and r["data"].get("min_fire_distance_m") is not None]
        if not d:
            continue
        mins = sorted(x["min_fire_distance_m"] for x in d)
        within = sum(1 for x in d if x["min_fire_distance_m"] < 1.0)
        lines.append(f"| {MODE_LABEL[m]} | {len(d)} | {mins[0]:.2f} / {mins[len(mins) // 2]:.2f} / {mins[-1]:.2f} | {within}/{len(d)} | "
                     f"{sum(x['time_within_1m_of_fire_s'] for x in d) / len(d):.1f} |")
    lines += ["", "## Paired comparisons on identical seeds (exposure, risk·s; negative = first mode is lower)", "",
              "| Comparison | Seeds | Mean difference | 95% bootstrap CI |", "|---|---|---|---|"]
    pairs = [("sensing", "baseline"), ("omniscient", "baseline"), ("sensing", "omniscient"), ("sensing", "sensing_notriage")]
    for a, b in pairs:
        if a not in modes or b not in modes:
            continue
        da = {r["seed"]: r["metrics"]["exposure_risk_s"] for r in modes[a] if r["metrics"] and r["outcome"] != "no_result"}
        db = {r["seed"]: r["metrics"]["exposure_risk_s"] for r in modes[b] if r["metrics"] and r["outcome"] != "no_result"}
        common = sorted(set(da) & set(db))
        if len(common) >= 3:
            mean, lo, hi = paired_bootstrap_ci([da[s] for s in common], [db[s] for s in common])
            summary.setdefault("paired_exposure", {})[f"{a}-{b}"] = {"seeds": common, "mean": mean, "ci": [lo, hi]}
            lines.append(f"| {MODE_LABEL[a]} − {MODE_LABEL[b]} | {len(common)} | {mean:+.2f} | {lo:+.2f} to {hi:+.2f} |")
    lines += ["", "## Planner cycle time (wall clock, all runs)", "", "| Mode | Cycles | Median (s) | p95 (s) | Max (s) |", "|---|---|---|---|---|"]
    for m, runs in modes.items():
        cyc = [c for r in runs for c in r["cycles"] if c > 0.02]
        if cyc:
            lines.append(f"| {MODE_LABEL[m]} | {len(cyc)} | {pct(cyc, 0.5):.2f} | {pct(cyc, 0.95):.2f} | {max(cyc):.2f} |")
    bad_runs = [(m, r) for m, runs in modes.items() for r in runs if r["outcome"] != "complete"]
    lines += ["", "## Runs that did not complete", ""]
    if not bad_runs:
        lines += ["None among the runs above."]
    else:
        lines += ["| Mode | Seed | Outcome | Points reached | Controller 'collision ahead' lines | 'Controller patience exceeded' | Last known position (m) |", "|---|---|---|---|---|---|---|"]
        for m, r in bad_runs:
            log = (root / m / f"seed_{r['seed']}" / "sim.log")
            text = log.read_text(errors="ignore") if log.is_file() else ""
            tl = (r.get("data") or {}).get("timeline") or []
            pos = f"({tl[-1][4]}, {tl[-1][5]})" if tl else "—"
            lines.append(f"| {m} | {r['seed']} | {r['outcome']} | {len((r.get('data') or {}).get('goals_reached', []))}/5 | "
                         f"{text.count('collision ahead')} | {text.count('patience exceeded')} | {pos} |")
    lines += ["", "## Per-run results", "", "| Mode | Seed | Outcome | Points | Exposure | Hit risk ≥ 0.92 (s) | Mission (s) | Cancelled | Exit |", "|---|---|---|---|---|---|---|---|---|"]
    for m, runs in modes.items():
        for r in runs:
            d = r.get("data", {})
            mt = r["metrics"] or {}
            lines.append(f"| {m} | {r['seed']} | {r['outcome']} | {len(d.get('goals_reached', []))}/{d.get('goals_total', '?')} | "
                         f"{mt.get('exposure_risk_s', '—')} | {mt.get('time_in_s', '—')} | {d.get('mission_s', '—')} | "
                         f"{d.get('routes_cancelled', '—')} | {r['exit']} |")
    few = [MODE_LABEL[m] for m, runs in modes.items() if len(runs) < 5]
    lines += ["", "## Reading this", ""]
    if few:
        lines += [f"- Fewer than 5 runs, shown for completeness only and excluded from the comparison paragraphs: {', '.join(few)}."]
    lines += [
              "- A run that never wrote a finished result is counted as a failure.",
              "- The sensor, the hazard model and the confidence estimate are simulated; these are simulation results.",
              "- With few runs per mode the intervals are wide; do not quote a percentage improvement from this table alone."]
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    (root / "summary.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
