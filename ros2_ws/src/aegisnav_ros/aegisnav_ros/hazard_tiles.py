"""Pure logic for drawing the *current* forecast layer as flat tiles in Gazebo.

The tiles are a rendering of `/aegisnav/hazard_forecast` (layer 0), never an input to
planning. They are visual-only (no collision), 1 cm thick at floor level — below the
lidar plane (0.28 m) — and carry visibility flags excluded by the lidar's visibility mask.
"""
from __future__ import annotations

from typing import Mapping, Sequence

from aegisnav_core.models import Cell

# Lower bounds of the drawn risk bands (normalized risk). Display thresholds only;
# planning uses PlannerConfig.hard_risk_threshold.
BAND_THRESHOLDS: tuple[float, ...] = (0.25, 0.5, 0.75)
# (r, g, b, alpha) per band: amber, orange, red.
BAND_COLORS: tuple[tuple[float, float, float, float], ...] = (
    (1.0, 0.75, 0.10, 0.45), (1.0, 0.40, 0.05, 0.65), (0.95, 0.08, 0.02, 0.85),
)
# Bit set on hazard visuals; the lidar's <visibility_mask> clears it.
HAZARD_VISIBILITY_FLAGS = 0x2


def risk_band(risk: float) -> int:
    """0 = not drawn, 1..len(BAND_THRESHOLDS) = increasing severity."""
    if not 0.0 <= risk <= 1.0:
        raise ValueError("risk must be in [0, 1]")
    return sum(risk >= t for t in BAND_THRESHOLDS)


def desired_bands(width: int, risk: Sequence[float], blocked: frozenset[int]) -> dict[Cell, int]:
    out = {}
    for idx, value in enumerate(risk):
        if idx in blocked:
            continue
        band = risk_band(value)
        if band:
            out[Cell(idx % width, idx // width)] = band
    return out


def cells_by_band(desired: Mapping[Cell, int]) -> dict[int, frozenset[Cell]]:
    """Group drawn cells by band; every band key is present (possibly empty)."""
    return {b: frozenset(c for c, band in desired.items() if band == b) for b in range(1, len(BAND_COLORS) + 1)}


def band_model_name(band: int, generation: int) -> str:
    """Unique per spawn, so a retry never collides with a model whose spawn reply was lost."""
    return f"aegisnav_hazard_band{band}_g{generation}"


def band_model_sdf(name: str, band: int, centres: Sequence[tuple[float, float]], size_m: float) -> str:
    """One static, collision-free model holding every tile of one band (one spawn call per band)."""
    if not 1 <= band <= len(BAND_COLORS):
        raise ValueError("band out of range")
    if size_m <= 0:
        raise ValueError("size_m must be positive")
    r, g, b, a = BAND_COLORS[band - 1]
    material = (f"<material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse>"
                f"<emissive>{r * 0.8:.2f} {g * 0.8:.2f} {b * 0.8:.2f} 1</emissive></material>")
    size = f"{size_m:.3f} {size_m:.3f} 0.010"
    visuals = "".join(
        f'<visual name="t{i}"><pose>{x:.3f} {y:.3f} 0.006 0 0 0</pose><cast_shadows>false</cast_shadows>'
        f"<visibility_flags>{HAZARD_VISIBILITY_FLAGS}</visibility_flags><transparency>{1.0 - a:.2f}</transparency>"
        f"<geometry><box><size>{size}</size></box></geometry>{material}</visual>"
        for i, (x, y) in enumerate(centres)
    )
    return (f'<?xml version="1.0"?><sdf version="1.9"><model name="{name}"><static>true</static>'
            f'<link name="link">{visuals}</link></model></sdf>')


# Display-only source effects. Particles: Gazebo particle emitters using the CC BY 4.0 Fuel "Fog Emitter" puff
# texture (models/fog_emitter) and colour-over-lifetime ramps generated by tools/generate_world_assets.py
# (models/aegisnav_effects); under Mesa/ogre2 they render as soft puffs (an earlier attempt without an alpha
# texture and colour ramp gave opaque squares). Emitters cannot carry visibility flags, and the gpu_lidar was
# observed to return particles even with particle_scatter_ratio 0 (or 0.0001) when the lowest particle edge was
# 0.04-0.09 m above the scan plane, but not at 0.49 m. So particles start PARTICLE_CLEARANCE_M above the highest
# lidar; everything lower is flagged geometry. Texture paths are absolute: the renderer did not resolve
# model:// for color_range_image on a model spawned from an SDF string.
LIDAR_PLANE_Z_M = 0.55  # highest 2D lidar among the robots: Husky 0.55 m (rescue_building), corridor bot 0.28 m (both checked against the world files by a test)
PARTICLE_CLEARANCE_M = 0.45
# Each emitter: (name, z m, emitter size m, particle size m, lifetime s, rate 1/s, min/max speed m/s (upward),
#                scale rate 1/s, colour ramp file)
_EMITTERS = {
    "fire": (
        ("flame", 1.2, 0.5, 0.4, 1.0, 70, 0.6, 1.0, 0.4, "fire_colors.png"),
        ("smoke", 2.0, 0.6, 0.7, 6.0, 5, 0.3, 0.5, 0.6, "smoke_colors.png"),
    ),
    "gas": (
        ("haze", 1.4, 0.6, 0.7, 6.0, 6, 0.05, 0.15, 0.1, "gas_colors.png"),
    ),
}
# Flagged geometry below the particles: (shape, radius m, length m, z centre m, rgb, emissive rgb, transparency)
_GEOMETRY_PARTS = {
    "fire": (
        ("cylinder", 0.4, 0.04, 0.02, "0.3 0.08 0.02", "1 0.35 0.05", 0.0),  # glowing ember bed
        ("cone", 0.35, 1.2, 0.6, "1 0.5 0.08", "1 0.5 0.08", 0.35),         # flame body up to the particles
        ("cone", 0.18, 0.8, 0.4, "1 0.85 0.3", "1 0.85 0.3", 0.2),          # hot core
    ),
    "gas": (
        ("cylinder", 0.9, 0.04, 0.02, "0.45 0.8 0.2", "0.18 0.32 0.08", 0.6),  # haze on the floor
        ("cylinder", 0.7, 1.0, 0.55, "0.5 0.85 0.25", "0.2 0.34 0.1", 0.82),   # thin column up to the cloud
    ),
}


def _bringup_models_dir() -> str:
    from ament_index_python.packages import get_package_share_directory
    return f"{get_package_share_directory('aegisnav_bringup')}/models"


def _emitter_sdf(spec: tuple, models_dir: str) -> str:
    name, z, size, psize, life, rate, vmin, vmax, scale, ramp = spec
    return (f'<particle_emitter name="{name}" type="box"><emitting>true</emitting>'
            f"<pose>0 0 {z} 0 -1.5707963 0</pose>"  # emitters emit along +x; pitch so +x points up
            f"<size>0 {size} {size}</size><particle_size>{psize} {psize} {psize}</particle_size>"
            f"<lifetime>{life}</lifetime><rate>{rate}</rate><min_velocity>{vmin}</min_velocity>"
            f"<max_velocity>{vmax}</max_velocity><scale_rate>{scale}</scale_rate>"
            f"<color_range_image>{models_dir}/aegisnav_effects/materials/textures/{ramp}</color_range_image>"
            f"<material><diffuse>1 1 1</diffuse><pbr><metal>"
            f"<albedo_map>{models_dir}/fog_emitter/materials/textures/fog.png</albedo_map></metal></pbr></material>"
            f"<particle_scatter_ratio>0</particle_scatter_ratio></particle_emitter>")


def effect_model_sdf(name: str, kind: str, *, models_dir: str | None = None) -> str:
    """Static visual-effect model for a hazard source: 'fire' (flame + smoke) or 'gas' (haze + cloud).

    Display only: no collision; particles stay PARTICLE_CLEARANCE_M above LIDAR_PLANE_Z_M and every
    visual carries HAZARD_VISIBILITY_FLAGS (the planner's input is the forecast topic). `models_dir` defaults to the
    installed aegisnav_bringup models directory.
    """
    emitters = _EMITTERS.get(kind)
    if emitters is None:
        raise ValueError("kind must be 'fire' or 'gas'")
    models_dir = (models_dir or _bringup_models_dir()).rstrip("/")
    visuals = []
    for i, (shape, radius, length, z, rgb, glow, transparency) in enumerate(_GEOMETRY_PARTS[kind]):
        visuals.append(
            f'<visual name="v{i}"><pose>0 0 {z} 0 0 0</pose><cast_shadows>false</cast_shadows>'
            f"<visibility_flags>{HAZARD_VISIBILITY_FLAGS}</visibility_flags><transparency>{transparency}</transparency>"
            f"<geometry><{shape}><radius>{radius}</radius><length>{length}</length></{shape}></geometry>"
            f"<material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse><emissive>{glow} 1</emissive></material></visual>")
    body = "".join(visuals) + "".join(_emitter_sdf(e, models_dir) for e in emitters)
    return (f'<?xml version="1.0"?><sdf version="1.9"><model name="{name}"><static>true</static>'
            f'<link name="l">{body}</link></model></sdf>')
